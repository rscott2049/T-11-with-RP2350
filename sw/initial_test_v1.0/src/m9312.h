/**
 * @brief Multi-ROM Unibus address mapping helper function.
 * 
 * @param address Current read address from the simulated Unibus.
 * @param base_offset The base configuration offset chosen for this ROM socket (e.g. 0173000, 0173200)
 * @param target_rom Choice of pointer matching m9312_rom_23_755a9 or m9312_rom_23_756a9.
 * @param word_out Decoded word destination if validation checks match.
 * @return int 1 on valid intercept, 0 if out of slot boundaries.
 */
static inline int m9312_read_boot_word(uint32_t address, uint32_t base_offset, 
                                       const uint16_t *target_rom, uint16_t *word_out) {
    uint32_t io_offset = address & 0xFFFF;
    
    if (io_offset >= base_offset && io_offset < (base_offset + M9312_BOOT_BYTES)) {
        uint32_t index = (io_offset - base_offset) >> 1;
        if (index < M9312_BOOT_WORDS) {
            *word_out = target_rom[index];
            return 1;
        }
    }
    return 0;
}

