/*
  Load absolute loader formatted memory array into target memory
  Memory array is assumed to be generated by bin2h, thus has the following
  format:
  unsigned char data[] = {... bytes of lda formatted data ...};
  unsigned int data_size = number of lda bytes

  returns:
  -2 on header not 0x01
  -3 on length less than 6
  -4 on checksum mismatch
  -1 for no initial pc
  >= 0 for initial pc from last block
  
From simh pdp11_sys.c sim_load function:

  Binary loader.

   Loader format consists of blocks, optionally preceded, separated, and
   followed by zeroes.  Each block consists of:

        001             ---
        xxx              |
        lo_count         |
        hi_count         |
        lo_origin        > count bytes
        hi_origin        |
        data byte        |
        :                |
        data byte       ---
        checksum

   If the byte count is exactly six, the block is the last on the tape, and
   there is no checksum.  If the origin is not 000001, then the origin is
   the PC at which to start the program.

*/   

#include "stdint.h"
#include "stdio.h"

int32_t load_lda(uint8_t *mem, uint8_t *lda_data) {
  uint32_t i = 0;
  int32_t len;
  uint32_t addr;
  uint32_t cksum;
  uint32_t blk_start;

  while(1) {
    // Save starting point
    blk_start = i;

    // Check for 0x01, 0x00 start of header
    if ((lda_data[i++] != 0x01) || (lda_data[i++] != 0x00)) return -2;
    else {

      // Get address/length (minus header bytes)
      len = (lda_data[i++] | (lda_data[i++] << 8)) - 6;
      addr = lda_data[i++] | (lda_data[i++] << 8);
      // Check for reasonableness
      if (len < 0) return -3;

      // Look for last block. (i.e. block with no data)
      // May contain transfer address
      if (len == 0) {
	if (addr != 0x01) return addr;
	else return -1;
      }

      // Initialize the checksum with the header bytes
      cksum = 0;
      for (int j = 0; j < 6; j++) {
	cksum += lda_data[blk_start + j];
      }

      // Ok, good. Now transfer bytes to memory
      for (int j = 0; j < len; j++) {
	mem[addr++] = lda_data[i];
	cksum += lda_data[i++];
      }

      // Byte after data is the checksum. If valid, low byte is zero
      cksum += lda_data[i++];
      if (cksum & 0xff != 0) return -4;
    }
  } 
}
